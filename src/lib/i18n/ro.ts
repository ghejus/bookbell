// like most Romanian booking apps). Same keys as en.ts.

const rules = new Intl.PluralRules("ro");

/** Time-zone cities Romanian customers know by their Romanian names. */
const ROMANIAN_CITIES: Record<string, string> = { Bucharest: "București", Chisinau: "Chișinău", Vienna: "Viena", Rome: "Roma", London: "Londra" };
/** 1 recenzie, 3 recenzii, 20 de recenzii (Romanian adds "de" from 20 on). */
export const roCount = (n: number, one: string, many: string) => {
  const kind = rules.select(n);
  return kind === "one" ? `${n} ${one}` : kind === "few" ? `${n} ${many}` : `${n} de ${many}`;
};

